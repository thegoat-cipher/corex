//! Token definitions for CoreX source text.

use crate::diagnostics::Span;

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TokenKind {
    Int(u64),
    Float(u64),
    Str(Vec<u8>),
    CharLit(u8),
    Ident(String),

    // Keywords.
    Fn,
    Import,
    Static,
    Const,
    Enum,
    Struct,
    Let,
    Mut,
    If,
    Else,
    While,
    Loop,
    Break,
    Continue,
    Return,
    Unsafe,
    As,
    True,
    False,

    // Primitive type names.
    I8,
    I16,
    I32,
    I64,
    U8,
    U16,
    U32,
    U64,
    Usize,
    Isize,
    Bool,
    Char,
    F32,
    F64,
    StrType,
    VecType,

    // Delimiters and punctuation.
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Semi,
    Colon,
    ColonColon,
    Dot,
    DotDot,
    Arrow,

    // Operators.
    Assign,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    AmpEq,
    PipeEq,
    CaretEq,
    ShlEq,
    ShrEq,
    EqEq,
    NotEq,
    Lt,
    Le,
    Gt,
    Ge,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Amp,
    AmpAmp,
    Pipe,
    PipePipe,
    Caret,
    Not,
    Shl,
    Shr,

    Eof,
}

impl TokenKind {
    /// Human-readable form used in "expected X, found Y" diagnostics.
    pub fn describe(&self) -> String {
        match self {
            TokenKind::Int(v) => format!("integer literal `{v}`"),
            TokenKind::Float(v) => format!("float literal `{}`", f64::from_bits(*v)),
            TokenKind::Str(_) => "string literal".to_string(),
            TokenKind::CharLit(c) => format!("character literal `{}`", (*c as char).escape_default()),
            TokenKind::Ident(name) => format!("identifier `{name}`"),
            TokenKind::Eof => "end of file".to_string(),
            other => format!("`{}`", other.symbol()),
        }
    }

    pub fn symbol(&self) -> &'static str {
        match self {
            TokenKind::Fn => "fn",
            TokenKind::Import => "import",
            TokenKind::Static => "static",
            TokenKind::Const => "const",
            TokenKind::Enum => "enum",
            TokenKind::Struct => "struct",
            TokenKind::Let => "let",
            TokenKind::Mut => "mut",
            TokenKind::If => "if",
            TokenKind::Else => "else",
            TokenKind::While => "while",
            TokenKind::Loop => "loop",
            TokenKind::Break => "break",
            TokenKind::Continue => "continue",
            TokenKind::Return => "return",
            TokenKind::Unsafe => "unsafe",
            TokenKind::As => "as",
            TokenKind::True => "true",
            TokenKind::False => "false",
            TokenKind::I8 => "i8",
            TokenKind::I16 => "i16",
            TokenKind::I32 => "i32",
            TokenKind::I64 => "i64",
            TokenKind::U8 => "u8",
            TokenKind::U16 => "u16",
            TokenKind::U32 => "u32",
            TokenKind::U64 => "u64",
            TokenKind::Usize => "usize",
            TokenKind::Isize => "isize",
            TokenKind::Bool => "bool",
            TokenKind::Char => "char",
            TokenKind::F32 => "f32",
            TokenKind::F64 => "f64",
            TokenKind::StrType => "str",
            TokenKind::VecType => "vec",
            TokenKind::LParen => "(",
            TokenKind::RParen => ")",
            TokenKind::LBrace => "{",
            TokenKind::RBrace => "}",
            TokenKind::LBracket => "[",
            TokenKind::RBracket => "]",
            TokenKind::Comma => ",",
            TokenKind::Semi => ";",
            TokenKind::Colon => ":",
            TokenKind::ColonColon => "::",
            TokenKind::Dot => ".",
            TokenKind::DotDot => "..",
            TokenKind::Arrow => "->",
            TokenKind::Assign => "=",
            TokenKind::PlusEq => "+=",
            TokenKind::MinusEq => "-=",
            TokenKind::StarEq => "*=",
            TokenKind::SlashEq => "/=",
            TokenKind::PercentEq => "%=",
            TokenKind::AmpEq => "&=",
            TokenKind::PipeEq => "|=",
            TokenKind::CaretEq => "^=",
            TokenKind::ShlEq => "<<=",
            TokenKind::ShrEq => ">>=",
            TokenKind::EqEq => "==",
            TokenKind::NotEq => "!=",
            TokenKind::Lt => "<",
            TokenKind::Le => "<=",
            TokenKind::Gt => ">",
            TokenKind::Ge => ">=",
            TokenKind::Plus => "+",
            TokenKind::Minus => "-",
            TokenKind::Star => "*",
            TokenKind::Slash => "/",
            TokenKind::Percent => "%",
            TokenKind::Amp => "&",
            TokenKind::AmpAmp => "&&",
            TokenKind::Pipe => "|",
            TokenKind::PipePipe => "||",
            TokenKind::Caret => "^",
            TokenKind::Not => "!",
            TokenKind::Shl => "<<",
            TokenKind::Shr => ">>",
            TokenKind::Int(_) => "integer literal",
            TokenKind::Float(_) => "float literal",
            TokenKind::Str(_) => "string literal",
            TokenKind::CharLit(_) => "character literal",
            TokenKind::Ident(_) => "identifier",
            TokenKind::Eof => "end of file",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Token {
        Token { kind, span }
    }
}
